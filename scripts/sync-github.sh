#!/usr/bin/env bash
# Push Forgejo's main to the GitHub mirror without the Forgejo-only .forgejo/
# directory. GitHub main = origin/main + one commit that deletes .forgejo, so
# every sync force-pushes GitHub main (guarded by --force-with-lease).
#
# Usage: scripts/sync-github.sh [--dry-run]
# Remotes: origin = Forgejo, github = GitHub.
set -euo pipefail

dry_run=false
[[ ${1:-} == --dry-run ]] && dry_run=true

git fetch -q origin main
git fetch -q github main
lease=$(git rev-parse github/main)

tree=$(mktemp -d)
trap 'git worktree remove --force "$tree" >/dev/null 2>&1 || true' EXIT
git worktree add -q --detach "$tree" origin/main

cd "$tree"
git rm -r -q .forgejo
git commit -q -m "Drop Forgejo-only CI from the GitHub mirror

GitHub runs .github/workflows; .forgejo/ only works on Forgejo.
Generated by scripts/sync-github.sh on top of $(git rev-parse --short origin/main)."
go test ./... >/dev/null

if $dry_run; then
	git log --oneline -2
	git show --stat --format= HEAD
	echo "dry run: not pushed"
else
	git push --force-with-lease="main:$lease" github HEAD:main
fi
